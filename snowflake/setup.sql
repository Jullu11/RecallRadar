-- Run in a Snowflake worksheet after creating a database + warehouse.
-- Lodestone copies confirmed purchases, recall decisions, and recovery actions here.

CREATE TABLE IF NOT EXISTS LODESTONE_PRODUCTS (
    PRODUCT_ID VARCHAR PRIMARY KEY,
    OWNER_HANDLE VARCHAR,
    BRAND VARCHAR,
    PRODUCT_NAME VARCHAR,
    STATUS VARCHAR,
    MONITORING_ENABLED BOOLEAN,
    SOURCE_TYPE VARCHAR,
    CREATED_AT TIMESTAMP_TZ,
    UPDATED_AT TIMESTAMP_TZ
);

CREATE TABLE IF NOT EXISTS LODESTONE_MATCHES (
    MATCH_KEY VARCHAR PRIMARY KEY,
    PRODUCT_ID VARCHAR,
    OWNER_HANDLE VARCHAR,
    DECISION VARCHAR,
    NOTICE_TITLE VARCHAR,
    OFFICIAL_URL VARCHAR,
    CHECKED_AT TIMESTAMP_TZ
);

CREATE TABLE IF NOT EXISTS LODESTONE_RECOVERY_CASES (
    CASE_ID VARCHAR PRIMARY KEY,
    PRODUCT_ID VARCHAR,
    OWNER_HANDLE VARCHAR,
    CASE_TYPE VARCHAR,
    DUE_DATE DATE,
    STATUS VARCHAR,
    CREATED_AT TIMESTAMP_TZ
);
